// Builds the Zephyra OS logo from one source: the mark geometry below + the "zephyra os" wordmark
// outlined from DM Sans Medium. Writes src/components/brand/logoPaths.ts and public/brand/*.
// Run: node scripts/build-logo.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import opentype from 'opentype.js'
import { Resvg } from '@resvg/resvg-js'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const INK = '#14121C'
const WASH = '#F6F4FF'
const GOLD = '#F2B43C'
const LAVENDER = '#DCD3FF'

// Mark, 32x32 grid: a coin (the "world" in zephyra.world) with three currents of wind cut through it,
// swirling around a sealed gold core. The breeze moves the money; the core stays private.
// The currents are real cut-outs (a mask), so the background shows through them.
export const MARK = {
  disc: 14,
  slit: 'M18.8 12.6Q24.6 6.4 31.2 12.8',
  count: 3,
  slitWidth: 2.6,
  coreGap: 4.6,
  core: 3.1,
}

/** SVG for the mark. `id` must be unique per document (the mask needs it). */
export function markSvg(id, disc = INK, core = GOLD) {
  const slits = Array.from(
    { length: MARK.count },
    (_, k) =>
      `<path d="${MARK.slit}" transform="rotate(${(360 / MARK.count) * k} 16 16)" fill="none" stroke="#000" stroke-width="${MARK.slitWidth}" stroke-linecap="round"/>`,
  ).join('')
  return (
    `<defs><mask id="${id}" maskUnits="userSpaceOnUse" x="0" y="0" width="32" height="32">` +
    `<rect width="32" height="32" fill="#fff"/>${slits}<circle cx="16" cy="16" r="${MARK.coreGap}" fill="#000"/></mask></defs>` +
    `<circle cx="16" cy="16" r="${MARK.disc}" fill="${disc}" mask="url(#${id})"/>` +
    `<circle cx="16" cy="16" r="${MARK.core}" fill="${core}"/>`
  )
}

// Wordmark: DM Sans Medium outlined to paths, tracking -0.02em, x-height centred on the mark.
const font = opentype.parse(readFileSync(join(root, 'scripts/fonts/DMSans-500.ttf')).buffer)
const SIZE = 26
const TRACK = -0.02 * SIZE
const xHeight = ((font.tables.os2.sxHeight || 500) / font.unitsPerEm) * SIZE
const baseline = 16 + xHeight / 2
const GAP = 8
let x = 32 + GAP
const parts = []
for (const ch of 'zephyra os') {
  const g = font.charToGlyph(ch)
  parts.push(g.getPath(x, baseline, SIZE).toPathData(2))
  x += (g.advanceWidth / font.unitsPerEm) * SIZE + TRACK
}
const WORD = parts.join('')
const FULL_W = Math.ceil(x - TRACK + 1)

mkdirSync(join(root, 'src/components/brand'), { recursive: true })
writeFileSync(
  join(root, 'src/components/brand/logoPaths.ts'),
  `// Generated by scripts/build-logo.mjs. Do not edit by hand.\n` +
    `export const MARK = ${JSON.stringify(MARK)} as const\n` +
    `export const WORD_PATH = ${JSON.stringify(WORD)}\n` +
    `export const LOGO_WIDTH = ${FULL_W}\n`,
)

const logoSvg = (ink, id) =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${FULL_W} 32" width="${FULL_W * 4}" height="128">${markSvg(id, ink)}<path fill="${ink}" d="${WORD}"/></svg>`
const markFile = (disc, id) => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32">${markSvg(id, disc)}</svg>`

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  mkdirSync(join(root, 'public/brand'), { recursive: true })
  writeFileSync(join(root, 'public/brand/logo.svg'), logoSvg(INK, 'zl'))
  writeFileSync(join(root, 'public/brand/logo-dark.svg'), logoSvg(LAVENDER, 'zld'))
  writeFileSync(join(root, 'public/brand/mark.svg'), markFile(INK, 'zm'))
  writeFileSync(join(root, 'public/brand/mark-dark.svg'), markFile(LAVENDER, 'zmd'))
  writeFileSync(
    join(root, 'public/favicon.svg'),
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32"><style>.d{fill:${INK}}@media (prefers-color-scheme:dark){.d{fill:${LAVENDER}}}</style>` +
      markSvg('zf', 'currentColor').replace(`fill="currentColor"`, `class="d"`) +
      `</svg>`,
  )

  // 500x500 exports: logo centred with ~12% padding
  const S = 500
  const pad = S * 0.12
  const scale = (S - 2 * pad) / FULL_W
  const h = 32 * scale
  const square = (bg) =>
    `<svg xmlns="http://www.w3.org/2000/svg" width="${S}" height="${S}" viewBox="0 0 ${S} ${S}">${bg ? `<rect width="${S}" height="${S}" fill="${bg}"/>` : ''}<g transform="translate(${pad} ${(S - h) / 2}) scale(${scale})">${markSvg('zs', INK)}<path fill="${INK}" d="${WORD}"/></g></svg>`
  for (const [name, bg] of [['logo-500.png', WASH], ['logo-500-transparent.png', null]]) {
    writeFileSync(join(root, 'public/brand', name), new Resvg(square(bg), { fitTo: { mode: 'original' } }).render().asPng())
  }
  // size checks (not shipped): the mark at 32px on light and dark
  writeFileSync(
    join(root, '.clone/mark-32.png'),
    new Resvg(
      `<svg xmlns="http://www.w3.org/2000/svg" width="72" height="32" viewBox="0 0 72 32"><rect width="72" height="32" fill="${WASH}"/>${markSvg('c1', INK)}<g transform="translate(40 0)"><rect width="32" height="32" fill="${INK}"/>${markSvg('c2', LAVENDER)}</g></svg>`,
      { fitTo: { mode: 'zoom', value: 4 } },
    )
      .render()
      .asPng(),
  )
  console.log('logo built', { FULL_W })
}
