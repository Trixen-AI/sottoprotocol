// Builds the Zephyra OS logo from one source: the mark geometry below + the "zephyra os" wordmark
// outlined from DM Sans Medium. Writes src/components/brand/logoPaths.ts and public/brand/*.
// Run: node scripts/build-logo.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import opentype from 'opentype.js'
import { Resvg } from '@resvg/resvg-js'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const INK = '#14121C'
const WASH = '#F6F4FF'

// Mark, 32x32 grid, drawn as one round-capped stroke: a Z whose top bar drifts in like a breeze and
// whose bottom bar lifts away at the end. Zephyr is the gentle west wind: money that moves quietly.
const MARK = 'M4.6 11.4C6 10.1 7.4 9.5 9.4 9.5H22L10 22.5H21.6C23.9 22.5 25.6 21.6 27.3 19.6'
const MARK_STROKE = 3.4

// Wordmark: DM Sans Medium outlined to paths, tracking -0.02em, x-height centred on the mark.
const font = opentype.parse(readFileSync(join(root, 'scripts/fonts/DMSans-500.ttf')).buffer)
const SIZE = 26
const TRACK = -0.02 * SIZE
const xHeight = ((font.tables.os2.sxHeight || 500) / font.unitsPerEm) * SIZE
const baseline = 16 + xHeight / 2
const GAP = 7.5
let x = 32 + GAP
const parts = []
for (const ch of 'zephyra os') {
  const g = font.charToGlyph(ch)
  parts.push(g.getPath(x, baseline, SIZE).toPathData(2))
  x += (g.advanceWidth / font.unitsPerEm) * SIZE + TRACK
}
const WORD = parts.join('')
const FULL_W = Math.ceil(x - TRACK + 1)
const wordWidth = x - 32 - GAP

mkdirSync(join(root, 'src/components/brand'), { recursive: true })
writeFileSync(
  join(root, 'src/components/brand/logoPaths.ts'),
  `// Generated by scripts/build-logo.mjs. Do not edit by hand.\n` +
    `export const MARK_PATH = ${JSON.stringify(MARK)}\n` +
    `export const MARK_STROKE = ${MARK_STROKE}\n` +
    `export const WORD_PATH = ${JSON.stringify(WORD)}\n` +
    `export const LOGO_WIDTH = ${FULL_W}\n`,
)

const markEl = (color) =>
  `<path d="${MARK}" fill="none" stroke="${color}" stroke-width="${MARK_STROKE}" stroke-linecap="round" stroke-linejoin="round"/>`
const logoSvg = (color) =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${FULL_W} 32" width="${FULL_W * 4}" height="128">${markEl(color)}<path fill="${color}" d="${WORD}"/></svg>`
const markSvg = (color) => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32">${markEl(color)}</svg>`

mkdirSync(join(root, 'public/brand'), { recursive: true })
writeFileSync(join(root, 'public/brand/logo.svg'), logoSvg(INK))
writeFileSync(join(root, 'public/brand/logo-dark.svg'), logoSvg('#DCD3FF'))
writeFileSync(join(root, 'public/brand/mark.svg'), markSvg(INK))
writeFileSync(
  join(root, 'public/favicon.svg'),
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32"><style>path{stroke:${INK}}@media (prefers-color-scheme:dark){path{stroke:#DCD3FF}}</style><path d="${MARK}" fill="none" stroke-width="${MARK_STROKE}" stroke-linecap="round" stroke-linejoin="round"/></svg>`,
)

// 500x500 exports: logo centred with ~12% padding
const S = 500
const pad = S * 0.12
const scale = (S - 2 * pad) / FULL_W
const h = 32 * scale
const square = (bg) =>
  `<svg xmlns="http://www.w3.org/2000/svg" width="${S}" height="${S}" viewBox="0 0 ${S} ${S}">${bg ? `<rect width="${S}" height="${S}" fill="${bg}"/>` : ''}<g transform="translate(${pad} ${(S - h) / 2}) scale(${scale})">${markEl(INK)}<path fill="${INK}" d="${WORD}"/></g></svg>`
for (const [name, bg] of [['logo-500.png', WASH], ['logo-500-transparent.png', null]]) {
  const png = new Resvg(square(bg), { fitTo: { mode: 'original' } }).render().asPng()
  writeFileSync(join(root, 'public/brand', name), png)
}
// favicon-size check render (not shipped): 32px mark on the wash
writeFileSync(
  join(root, '.clone/mark-32.png'),
  new Resvg(`<svg xmlns="http://www.w3.org/2000/svg" width="32" height="32" viewBox="0 0 32 32"><rect width="32" height="32" fill="${WASH}"/>${markEl(INK)}</svg>`, { fitTo: { mode: 'zoom', value: 4 } }).render().asPng(),
)
console.log('logo built', { FULL_W, wordWidth: wordWidth.toFixed(1) })
